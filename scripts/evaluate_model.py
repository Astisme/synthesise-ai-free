#!/usr/bin/env python3
"""Grade captured model/harness outputs without making API calls.

Run scenarios in the target agent harness separately. This tool validates the
capture, checks simple required/forbidden markers, validates aggregate rubric
scores, and emits reproducibility metadata. Marker checks are not semantic evaluation.
"""
from __future__ import annotations
import argparse
import hashlib
import json
from datetime import datetime, timezone
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
SCENARIOS = ROOT / "evaluations/scenarios"
RUBRICS = ROOT / "evaluations/rubrics"
REQUIRED_RUBRICS = {"methodology", "evidence-quality", "output-quality"}


def load(path):
    return json.loads(path.read_text(encoding="utf-8"))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input", type=Path, help="Captured model-run JSON; see fixtures/model-run.example.json")
    parser.add_argument("--report", type=Path, help="Output report path (defaults to stdout)")
    args = parser.parse_args()
    try:
        data = load(args.input)
        required = ("model", "harness", "configuration", "scenario_set", "rubric_version", "results")
        missing = [key for key in required if key not in data]
        if missing:
            raise ValueError("Missing fields: " + ", ".join(missing))
        if not isinstance(data["results"], list) or not data["results"]:
            raise ValueError("results must be a non-empty array")
        scenario_map = {}
        for path in SCENARIOS.glob("*.yaml"):
            scenario = load(path)
            scenario_map[scenario["id"]] = scenario
        rubric_names = {path.stem for path in RUBRICS.glob("*.yaml")}
        if not REQUIRED_RUBRICS.issubset(rubric_names):
            raise ValueError("One or more required rubric files are missing")
        results, errors = [], []
        for run in data["results"]:
            scenario_id = run["scenario_id"]
            if scenario_id not in scenario_map:
                errors.append(f"Unknown scenario: {scenario_id}")
                continue
            scenario = scenario_map[scenario_id]
            output = run["output"].casefold()
            missing_markers = [item for item in scenario["expected"]["required_output_elements"]
                               if item.casefold() not in output]
            forbidden_markers = [item for item in scenario["expected"]["forbidden_behaviours"]
                                 if item.casefold() in output]
            scores = run.get("scores", {})
            missing_scores = sorted(REQUIRED_RUBRICS - set(scores))
            extra_scores = sorted(set(scores) - REQUIRED_RUBRICS)
            invalid_scores = {key: value for key, value in scores.items()
                              if not isinstance(value, int) or isinstance(value, bool) or not 1 <= value <= 5}
            if missing_scores or extra_scores or invalid_scores:
                errors.append(f"{scenario_id}: score error; missing={missing_scores}, extra={extra_scores}, invalid={invalid_scores}")
            results.append({
                "scenario_id": scenario_id,
                "marker_check": "passed" if not missing_markers and not forbidden_markers else "failed",
                "missing_required_markers": missing_markers,
                "forbidden_markers_found": forbidden_markers,
                "rubric_scores": scores
            })
        config_bytes = json.dumps(data["configuration"], sort_keys=True, separators=(",", ":")).encode()
        report = {
            "evaluation_version": "1.0.0",
            "skill_version": data.get("skill_version", "1.1.0"),
            "model": data["model"],
            "harness": data["harness"],
            "configuration_hash": "sha256:" + hashlib.sha256(config_bytes).hexdigest(),
            "scenario_set": data["scenario_set"],
            "rubric_version": data["rubric_version"],
            "evaluation_date": datetime.now(timezone.utc).date().isoformat(),
            "evaluation_method": "captured-output marker checks plus supplied 1-5 rubric scores; semantic scores are not generated by this script",
            "rubrics_available": sorted(rubric_names),
            "results": results,
            "errors": errors,
            "passed": not errors and all(result["marker_check"] == "passed" for result in results)
        }
        rendered = json.dumps(report, indent=2) + "\n"
        if args.report:
            args.report.parent.mkdir(parents=True, exist_ok=True)
            args.report.write_text(rendered, encoding="utf-8")
        else:
            print(rendered, end="")
        return 1 if errors or not report["passed"] else 0
    except (OSError, json.JSONDecodeError, KeyError, TypeError, ValueError) as exc:
        print(f"Model evaluation input error: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
